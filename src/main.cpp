#include <Arduino.h>
#include "rgb_strip.h"

/**
 * Функція ініціалізації Arduino.
 * Викликається один раз при запуску мікроконтролера.
 * Тут виконується налаштування всіх компонентів системи.
 */
void setup()
{
    RGB_strip_Init(); // Ініціалізація світлодіодних смуг та пов'язаних компонентів
}

/**
 * Основний цикл програми Arduino.
 * Викликається постійно після setup().
 * Тут обробляється логіка оновлення стану системи.
 */
void loop()
{
    RGB_strip_Update(); // Оновлення стану світлодіодних смуг (обробка вводу, рендеринг)
}
