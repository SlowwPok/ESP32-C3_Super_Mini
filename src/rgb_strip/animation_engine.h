#pragma once
#include <Arduino.h>
#include "rgb_strip/rgb_strip.h"
#include "rgb_strip/rgb_types.h"

/* =========================================================
   СТАН АНІМАЦІЇ
   ========================================================= */

/*
  AnimationState — ОКРЕМИЙ СТАН ДЛЯ КОЖНОГО РЕЖИМУ

  Навіщо:
  - кожна анімація памʼятає свій індекс
  - глітч не "перескакує" при зміні режимів
  - можна мати кілька анімацій одночасно в майбутньому
  - дозволяє незалежну роботу для кожної смуги при необхідності
*/

/**
 * Структура стану анімації.
 * Зберігає поточний стан анімації для кожного режиму окремо.
 * Це дозволяє кожному режиму мати власну анімацію без конфліктів.
 *
 * Кожна смуга может мати окремий стан для асиметричних ефектів.
 */
struct AnimationState
{
    // Основні параметри анімації
    uint16_t index;         // Основний індекс анімації (наприклад, позиція ходячого пікселя)
    float phase;            // Фаза анімації (0.0-∞) для плавних переходів, хвиль та шуму
    unsigned long lastStep; // Час останнього кроку анімації (для керування швидкістю)

    // Параметри для специфічних анімацій
    bool evenPhase;         // Фаза для парних/непарних анімацій (чергування паритету)

    // Стан гліч-ефекту (для ANIM_GLITCH)
    bool glitchActive;         // Чи активний гліч в даний момент (true - активна)
    uint8_t glitchPixel;       // Індекс пікселя, з якого починається гліч
    uint8_t glitchCount;       // Кількість послідовних пікселів, які беруть участь у глічі
    unsigned long glitchUntil; // Час завершення глічу (в мілісекундах, поточний час)
};

/* =========================================================
   API АНІМАЦІЙНОГО ДВИГУНА
   ========================================================= */

/**
 * Ініціалізує стан анімації початковими значеннями.
 * Скидає всі лічильники та прапорці для початку нової анімації.
 * Викликається один раз при запуску для кожної смуги/режиму.
 *
 * @param s Посилання на стан анімації для ініціалізації
 */
void Animation_Init(AnimationState& s);

/**
 * Оновлює стан анімації на основі поточного часу та параметрів.
 * Обробляє рух пікселів, оновлення фази та логіку спеціальних ефектів.
 * Викликається регулярно під час рендеринга (у loop).
 *
 * Внутрішня логіка:
 * - Перевіряє час з останнього кроку
 * - Оновлює індекс та фазу для плавного руху
 * - Обробляє специфічну логіку залежно від типу анімації
 *
 * @param s Посилання на стан анімації для оновлення
 * @param p Параметри анімації (тип, швидкість, інтенсивність тощо)
 */
void Animation_Update(AnimationState& s, const AnimationParams& p);

/**
 * Застосовує ефект анімації до базового кольору конкретного пікселя.
 * Переводить базовий колір через анімаційний фільтр залежно від типу.
 * Повертає модифікований колір для відображення на пікселі.
 *
 * Типи анімацій та їх логіка:
 * - WALKING_PIXEL: один яскравий піксель рухається, інші приглушені
 * - EVEN_ODD: чергування парних/непарних пікселів
 * - GLITCH: випадкові спалахи для імітації збою
 * - PULSE: плавна осцеляція яскравості
 * - WAVE: косинусна хвиля, що рухається
 * - NOISE: органічний шум з комбінацією синусів
 *
 * @param s Стан анімації з поточним індексом, фазою тощо
 * @param p Параметри анімації (тип, швидкість, інтенсивність, режими)
 * @param base Базовий колір пікселя з режиму (MODE_PER_PIXEL або MODE_SOLID)
 * @param pixelIndex Індекс пікселя у смузі (0 до NUMPIXELS-1)
 * @param isSecondStrip Чи це друга смуга (для інверсії напрямку/фази)
 * @return RGB Результуючий колір після застосування анімації
 */
RGB Animation_Apply(
  const AnimationState& s, 
  const AnimationParams& p, 
  const RGB& base, 
  uint8_t pixelIndex,
  bool isSecondStrip
);
