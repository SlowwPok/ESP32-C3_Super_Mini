#pragma once
#include <Arduino.h>
#include <Adafruit_NeoPixel.h>
#include "rgb_strip/rgb_types.h"
#include "rgb_strip/animation_engine.h"

/* =========================================================
   КОНФІГУРАЦІЯ ПРОЕКТУ
   ========================================================= */

// Геометрія та кількість світлодіодів
#define NUMPIXELS 8        // Кількість WS2812B світлодіодів (NeoPixel) у кожній смузі

// Піни мікроконтролера ESP32-C3
#define LED_1_PIN 2        // GPIO 2: Пін для першої світлодіодної смуги (лівий канал)
#define LED_2_PIN 3        // GPIO 3: Пін для другої світлодіодної смуги (правий канал)

// Сенсорна кнопка та прапорці
#define TOUCH_PIN 4         // GPIO 4: Пін для сенсорної кнопки (дотик/натискання)
#define LONG_PRESS_TIME 800 // Час довгого натискання в мілісекундах (800 мс)
                            // Коротке натискання (TAP): < 800 мс → перемикання режиму
                            // Довге натискання (LONG): >= 800 мс → увімкнення/вимкнення

/* =========================================================
   ТИПИ РЕЖИМІВ ОСВІТЛЕННЯ
   ========================================================= */

/**
 * Перелік типів режимів освітлення.
 * Визначає, як буде відображатися колір на світлодіодних смугах.
 * 
 * Кожен тип має свою структуру даних у союзі RGBMode:
 * - MODE_SOLID → використовується поле .solid
 * - MODE_PER_PIXEL → використовується поле .perPixel
 * - MODE_ANIMATED → використовується поле .animated
 */
enum RGBModeType
{
    MODE_SOLID,     // Суцільний колір: один колір на всю смугу (простий, енергозбережуючий)
    MODE_PER_PIXEL, // По пікселях: кожен піксель може мати свій колір (градієнти, паттерни)
    MODE_ANIMATED   // Анімований: анімація поверх базового режиму (динамічні ефекти)
};

/* =========================================================
   СТРУКТУРА РЕЖИМУ ОСВІТЛЕННЯ
   ========================================================= */

/**
 * Основна структура режиму освітлення.
 * Містить всі необхідні дані для відображення режиму на світлодіодних смугах.
 * 
 * Архітектура:
 * - Завжди присутні: selectable, type, brightness
 * - Данні залежно від типу: solid, perPixel або animated (перекриваючий union)
 * 
 * Це дозволяє ефективно зберігати режими в пам'яті FLASH (PROGMEM),
 * оскільки не всі поля потрібні одночасно.
 */
struct RGBMode
{
    bool selectable;     // Чи доступний режим для вибору користувачем кнопкою
                         // true = режим буде показуватися при переборі (TAP)
                         // false = службовий режим (для внутрішнього використання як база для анімацій)
    
    RGBModeType type;    // Тип режиму: суцільний, по пікселях, або анімований
    
    uint8_t brightness;  // Загальна яскравість режиму (0-255)
                         // 0 = повністю темно (всі світлодіоди вимкнені)
                         // 255 = максимальна яскравість
                         // Значення застосовується до всіх пікселів режиму

    /**
     * Об'єднання (union) для різних типів даних залежно від режиму.
     * Використовується для економії пам'яті - тільки один варіант активний одночасно.
     * 
     * Розмір: 16 байт (розмір найбільшого варіанту perPixel)
     * - solid: 6 байт (2 RGB × 3 байти)
     * - perPixel: 48 байт (16 RGB × 3 байти)
     * - animated: 12 байт (1 uint8 + 1 AnimationParams)
     */
    union
    {
        // Дані для MODE_SOLID: один колір для обох смуг
        // Приклад: теплий вечір, ніч
        struct
        {
            RGB strip1; // Колір для першої смуги (лівої)
            RGB strip2; // Колір для другої смуги (правої)
        } solid;

        // Дані для MODE_PER_PIXEL: масив кольорів по пікселях
        // Кожен піксель на кожній смузі має унікальний колір
        // Приклад: веселкові градієнти, неонові ефекти
        struct
        {
            RGB strip1[NUMPIXELS]; // Масив кольорів для першої смуги (8 пікселів)
            RGB strip2[NUMPIXELS]; // Масив кольорів для другої смуги (8 пікселів)
        } perPixel;

        // Дані для MODE_ANIMATED: анімація поверх базового режиму
        // Базовий режим повинен бути MODE_PER_PIXEL
        // Анімація змінює вихідні кольори в реальному часі
        struct
        {
            uint8_t baseModeIndex; // Індекс базового кольорового режиму (режим 0-N)
                                   // Повинен вказувати на режим з type == MODE_PER_PIXEL
                                   // Анімація застосовується до його кольорів
            
            AnimationParams anim;  // Параметри анімації (тип, швидкість, інтенсивність тощо)
                                   // Див. rgb_types.h для деталей
        } animated;
    };
};

/* =========================================================
   ПУБЛІЧНИЙ API (ІНТЕРФЕЙС ДЛЯ ЗОВНІШНЬОГО ВИКОРИСТАННЯ)
   ========================================================= */

/**
 * Ініціалізує світлодіодні смуги та всі пов'язані компоненти.
 * Викликається один раз при запуску системи (у setup()).
 * 
 * Внутрішня логіка:
 * 1. Ініціалізує NeoPixel об'єкти для обох смуг
 * 2. Встановлює піни для сенсорної кнопки
 * 3. Ініціалізує стани анімацій для всіх режимів
 * 4. Показує початковий режим на світлодіодах
 * 
 * @note Не потребує параметрів, використовує глобальні константи з #define
 */
void RGB_strip_Init();

/**
 * Основний цикл оновлення стану світлодіодних смуг.
 * Викликається регулярно в loop() Arduino програми.
 * Повинна викликатися якомога частіше для плавної анімації та чутливої кнопки.
 * 
 * Внутрішня логіка:
 * 1. Читає стан сенсорної кнопки і визначає тип натискання (TAP / LONG)
 * 2. Обробляє команди від користувача:
 *    - TOUCH_LONG: вмикає/вимикає світлодіоди (toggle LED state)
 *    - TOUCH_TAP: перемикає на наступний доступний режим (селектабельний)
 * 3. Рендерує поточний режим на обидві смуги
 * 4. Оновлює анімації, якщо режим анімований
 * 
 * Рекомендована частота виклику:
 * - Мінімум: > 10 Hz (100 мс) для видимого оновлення
 * - Оптимум: > 50 Hz (20 мс) для плавної анімації
 * - В loop() без затримок: ~1000+ Hz (залежить від швидкості мікроконтролера)
 */
void RGB_strip_Update();
