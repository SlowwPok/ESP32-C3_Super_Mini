#pragma once
#include <Arduino.h>
#include <Adafruit_NeoPixel.h>
#include "rgb_strip/rgb_types.h"
#include "rgb_strip/animation_engine.h"

/* =========================================================
   КОНФІГУРАЦІЯ ПРОЕКТУ
   ========================================================= */

#define NUMPIXELS 8        // Кількість світлодіодів у кожній смузі

#define LED_1_PIN 2        // Пін для першої світлодіодної смуги
#define LED_2_PIN 3        // Пін для другої світлодіодної смуги

#define TOUCH_PIN 4        // Пін для сенсорної кнопки
#define LONG_PRESS_TIME 800 // Час довгого натискання в мілісекундах (800 мс)

/* =========================================================
   ТИПИ РЕЖИМІВ ОСВІТЛЕННЯ
   ========================================================= */

/**
 * Перелік типів режимів освітлення.
 * Визначає, як буде відображатися колір на світлодіодних смугах.
 */
enum RGBModeType
{
    MODE_SOLID,     // Суцільний колір: один колір на всю смугу
    MODE_PER_PIXEL, // По пікселях: кожен піксель має свій колір
    MODE_ANIMATED   // Анімований: анімація поверх базового режиму
};

/* =========================================================
   СТРУКТУРА РЕЖИМУ ОСВІТЛЕННЯ
   ========================================================= */

/**
 * Основна структура режиму освітлення.
 * Містить всі необхідні дані для відображення режиму на світлодіодних смугах.
 */
struct RGBMode
{
    bool selectable;     // Чи доступний режим для вибору користувачем (true - так)
    RGBModeType type;    // Тип режиму (суцільний, по пікселях, анімований)
    uint8_t brightness;  // Загальна яскравість режиму (0-255)

    /**
     * Об'єднання для різних типів даних залежно від режиму.
     * Використовується для економії пам'яті - тільки один варіант активний.
     */
    union
    {
        // Дані для MODE_SOLID: суцільний колір
        struct
        {
            RGB strip1; // Колір для першої смуги
            RGB strip2; // Колір для другої смуги
        } solid;

        // Дані для MODE_PER_PIXEL: масив кольорів по пікселях
        struct
        {
            RGB strip1[NUMPIXELS]; // Масив кольорів для першої смуги
            RGB strip2[NUMPIXELS]; // Масив кольорів для другої смуги
        } perPixel;

        // Дані для MODE_ANIMATED: анімація поверх базового режиму
        struct
        {
            uint8_t baseModeIndex; // Індекс базового кольорового режиму
            AnimationParams anim;  // Параметри анімації
        } animated;
    };
};

/* =========================================================
   ПУБЛІЧНИЙ API (ІНТЕРФЕЙС ДЛЯ ЗОВНІШНЬОГО ВИКОРИСТАННЯ)
   ========================================================= */

/**
 * Ініціалізує світлодіодні смуги та всі пов'язані компоненти.
 * Викликається один раз при запуску системи.
 */
void RGB_strip_Init();

/**
 * Оновлює стан світлодіодних смуг.
 * Обробляє введення користувача та оновлює відображення.
 * Викликається регулярно в основному циклі.
 */
void RGB_strip_Update();
