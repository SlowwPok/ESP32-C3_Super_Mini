#pragma once
#include <Arduino.h>

/* =========================================================
   БАЗОВІ ТИПИ ДАНИХ
   ========================================================= */

/**
 * Структура для представлення RGB кольору.
 * Використовується для зберігання значень червоного, зеленого та синього каналів.
 * Підтримує роботу з Adafruit NeoPixel та іншими бібліотеками світлодіодів.
 */
struct RGB
{
    uint8_t r; // Червоний канал (0-255)
    uint8_t g; // Зелений канал (0-255)
    uint8_t b; // Синій канал (0-255)
};

/* =========================================================
   ТИПИ АНІМАЦІЙ
   ========================================================= */

/**
 * Перелік типів анімацій для динамічних ефектів.
 * Визначає різні способи зміни кольорів та яскравості з часом.
 * Кожен тип створює унікальний візуальний ефект.
 */
enum AnimationType
{
    ANIM_WALKING_PIXEL, // Ходячий піксель: один яскравий піксель рухається вздовж смуги
    ANIM_EVEN_ODD,      // Парні/непарні: чергування кольорів за індексом пікселя
    ANIM_GLITCH,        // Гліч: випадкові спалахи, імітація цифрового збою
    ANIM_PULSE,         // Пульс: поступове збільшення та зменшення яскравості
    ANIM_WAVE,          // Хвиля: косинусоїдний рух по смузі
    ANIM_NOISE,         // Шум: випадкові флюктуації кольору
};

/**
 * Структура параметрів анімації.
 * Містить усі налаштування для керування поведінкою анімації.
 * Дозволяє тонко налаштовувати кожен аспект ефекту.
 */
struct AnimationParams
{
    AnimationType type;   // Тип анімації для використання
    uint16_t speedMs;     // Швидкість анімації в мілісекундах між кадрами
    bool syncStrips;      // Чи синхронізовані обидві смуги (true - одна анімація, false - окремі)
    bool invertSecond;    // Чи інвертувати напрямок/фазу для другої смуги
    uint8_t intensity;    // Інтенсивність ефекту: 1-10 (1=мінімальна, 10=максимальна)
    bool invertEffect;    // Чи інвертувати ефект анімації (наприклад, темне замість світлого)
};