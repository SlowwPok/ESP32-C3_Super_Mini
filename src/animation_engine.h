#pragma once
#include <Arduino.h>
#include <rgb_strip.h>

/* =========================================================
   ТИПИ АНІМАЦІЙ
   ========================================================= */

/**
 * Перелік типів анімацій для динамічних ефектів.
 * Визначає різні способи зміни кольорів з часом.
 */
enum AnimationType
{
    ANIM_WALKING_PIXEL, // Ходячий піксель: один яскравий піксель рухається вздовж смуги
    ANIM_EVEN_ODD,      // Парні/непарні: чергування кольорів по парності індексу
    ANIM_GLITCH         // Гліч: випадкові спалахи, імітація цифрового збою
};

/**
 * Структура параметрів анімації.
 * Містить налаштування для керування поведінкою анімації.
 */
struct AnimationParams
{
    AnimationType type;   // Тип анімації
    uint16_t speedMs;     // Швидкість анімації в мілісекундах між кадрами
    bool syncStrips;      // Чи синхронізовані смуги (true - так, false - ні)
    bool invertSecond;    // Чи інвертувати другу смугу (для різноманітності)
    uint8_t intensity;    // Інтенсивність ефекту (1-10, де 10 - максимальна)
};

/*
  AnimationState — ОКРЕМИЙ СТАН ДЛЯ КОЖНОГО РЕЖИМУ

  Навіщо:
  - кожна анімація памʼятає свій індекс
  - глітч не "перескакує" при зміні режимів
  - можна мати кілька анімацій одночасно в майбутньому
*/

/**
 * Структура стану анімації.
 * Зберігає поточний стан анімації для кожного режиму окремо.
 * Це дозволяє кожному режиму мати власну анімацію без конфліктів.
 */
struct AnimationState
{
    uint16_t index;         // Основний індекс анімації (наприклад, позиція ходячого пікселя)
    float phase;            // Фаза анімації (для плавних переходів або хвиль)
    unsigned long lastStep; // Час останнього кроку анімації (для керування швидкістю)

    // Стан гліч-ефекту
    bool glitchActive;      // Чи активний гліч в даний момент
    uint8_t glitchPixel;    // Індекс пікселя, з якого починається гліч
    uint8_t glitchCount;    // Кількість пікселів, які беруть участь у глічі
    unsigned long glitchUntil; // Час завершення глічу (в мілісекундах)
};

/* =========================================================
   API АНІМАЦІЙНОГО ДВИГУНА
   ========================================================= */

/**
 * Ініціалізує стан анімації початковими значеннями.
 * Скидає всі лічильники та прапорці для початку нової анімації.
 *
 * @param s Посилання на стан анімації для ініціалізації
 */
void Animation_Init(AnimationState& s);

/**
 * Оновлює стан анімації на основі поточного часу та параметрів.
 * Обробляє рух пікселів та логіку спеціальних ефектів (наприклад, гліч).
 *
 * @param s Посилання на стан анімації для оновлення
 * @param p Параметри анімації (тип, швидкість тощо)
 */
void Animation_Update(AnimationState& s, const AnimationParams& p);

/**
 * Застосовує ефект анімації до базового кольору конкретного пікселя.
 * Залежно від типу анімації змінює колір або повертає базовий.
 *
 * @param s Стан анімації
 * @param p Параметри анімації
 * @param base Базовий колір пікселя
 * @param pixelIndex Індекс пікселя (0 до NUMPIXELS-1)
 * @return RGB Результуючий колір після застосування анімації
 */
RGB Animation_Apply(const AnimationState& s, const AnimationParams& p, const RGB& base, uint8_t pixelIndex);
