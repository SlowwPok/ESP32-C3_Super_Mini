/**
 * Структура для представлення RGB кольору.
 * Використовується для зберігання значень червоного, зеленого та синього каналів.
 */
struct RGB
{
    uint8_t r; // Червоний канал (0-255)
    uint8_t g; // Зелений канал (0-255)
    uint8_t b; // Синій канал (0-255)
};